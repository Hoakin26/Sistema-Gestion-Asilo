        ruta_archivo varchar(100),
        indicaciones varchar(500),
        nombre_archivo varchar(255),
        resultado text,
        primary key (id)
    );

    create table pago (
        anulado boolean not null default false not null,
        fecha date not null,
        monto numeric(10,2) not null,
        anulado_por_id bigint,
