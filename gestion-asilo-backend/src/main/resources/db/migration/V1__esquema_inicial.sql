    create table notificacion_familiar (
        intentos integer not null,
        fecha_creacion timestamp(6) not null,
        fecha_envio timestamp(6),
        fecha_ultimo_intento timestamp(6),
        id bigint generated by default as identity,
        solicitud_id bigint not null,
        estado varchar(20) not null check ((estado in ('PENDIENTE','ENVIADA','FALLIDA','SIN_CORREO'))),
        tipo varchar(30) not null check ((tipo in ('SOLICITUD_CREADA','CITA_ASIGNADA'))),
        destinatario varchar(150),
        ultimo_error varchar(500),
        primary key (id)
