
    create table cargo_servicio (
        descuento numeric(10,2) not null,
        fecha date not null,
        monto_neto numeric(10,2) not null,
        monto_original numeric(10,2) not null,
        cuenta_id bigint,
        fecha_creacion timestamp(6) not null,
        id bigint generated by default as identity,
        interno_id bigint not null,
        visita_id bigint not null,
        tipo varchar(20) not null check ((tipo in ('CONSULTA','LABORATORIO','FARMACIA'))),
        primary key (id)
    );

    create table cita (
        duracion_minutos integer not null,
        asignada_por_id bigint not null,
        especialista_id bigint not null,
        fecha_creacion timestamp(6) not null,
        fecha_hora timestamp(6) not null,
        id bigint generated by default as identity,
        solicitud_id bigint not null unique,
        primary key (id),
        constraint uk_cita_especialista_hora unique (especialista_id, fecha_hora)
    );

    create table contador_solicitud (
        anio integer not null,
        ultimo integer not null,
        primary key (anio)
    );

    create table cuenta_mensual (
        cuota_base numeric(10,2) not null,
        saldo numeric(10,2) not null,
        total_a_pagar numeric(10,2) not null,
        total_descuentos numeric(10,2) not null,
        total_pagado numeric(10,2) default 0 not null,
        total_servicios numeric(10,2) not null,
        periodo varchar(7) not null,
        familiar_id bigint not null,
        fecha_consolidacion timestamp(6) not null,
        id bigint generated by default as identity,
        interno_id bigint not null,
        version bigint not null,
        estado varchar(30) not null check ((estado in ('PENDIENTE_PAGO','PAGO_PARCIAL','COMPLETAMENTE_CANCELADA','EN_MORA'))),
        primary key (id),
        constraint uk_cuenta_interno_periodo unique (interno_id, periodo)
    );

    create table cuenta_por_pagar (
        total_pagado numeric(10,2) not null,
        periodo varchar(7) not null,
        fecha_creacion timestamp(6) not null,
        id bigint generated by default as identity,
        version bigint not null,
        tipo_servicio varchar(20) not null check ((tipo_servicio in ('CONSULTA','LABORATORIO','FARMACIA'))),
        primary key (id),
        constraint uk_cuenta_por_pagar_periodo_tipo unique (periodo, tipo_servicio)
    );

    create table detalle_receta (
        cantidad integer not null,
        costo numeric(10,2),
        entregado boolean not null default false not null,
        fecha_entrega timestamp(6),
        id bigint generated by default as identity,
        receta_id bigint not null,
        dosis varchar(100) not null,
        medicamento varchar(150) not null,
        forma_aplicacion varchar(200) not null,
        primary key (id)
    );

    create table donacion (
        anulada boolean default false not null,
        fecha date not null,
        monto numeric(12,2) not null,
        anulada_por_id bigint,
        fecha_anulacion timestamp(6),
        fecha_registro timestamp(6) not null,
        id bigint generated by default as identity,
        registrada_por_id bigint not null,
        tipo_donante varchar(30) not null check ((tipo_donante in ('EMPRESA_INTERNACIONAL','EMPRESA_NACIONAL','GOBIERNO','PARTICULAR'))),
        donante varchar(150) not null,
        motivo_anulacion varchar(300),
        primary key (id)
    );

    create table especialidad (
        activa boolean not null,
        tarifa_consulta numeric(10,2),
        id bigint generated by default as identity,
        nombre varchar(100) not null unique,
        primary key (id)
    );

    create table examen_laboratorio (
        activo boolean not null,
        costo_referencia numeric(10,2) not null,
        id bigint generated by default as identity,
        nombre varchar(150) not null unique,
        primary key (id)
    );

    create table familiar (
        id bigint generated by default as identity,
        telefono varchar(20) not null,
        parentesco varchar(50) not null,
        correo varchar(150),
        nombre_completo varchar(150) not null,
        direccion varchar(200),
        primary key (id)
    );

    create table ficha_medica (
        tipo_sangre varchar(5),
        fecha_actualizacion timestamp(6) not null,
        fecha_creacion timestamp(6) not null,
        id bigint generated by default as identity,
        interno_id bigint not null unique,
        alergias varchar(500),
        motivo_ingreso varchar(500),
        primary key (id)
    );

    create table gasto_operativo (
        anulado boolean default false not null,
        fecha date not null,
        monto numeric(12,2) not null,
        anulado_por_id bigint,
        fecha_anulacion timestamp(6),
        fecha_registro timestamp(6) not null,
        id bigint generated by default as identity,
        registrado_por_id bigint not null,
        tipo_gasto varchar(30) not null check ((tipo_gasto in ('LUZ','AGUA','TELEFONO_INTERNET','GAS','ALIMENTACION','LIMPIEZA','MANTENIMIENTO','OTRO'))),
        descripcion varchar(200),
        motivo_anulacion varchar(300),
        primary key (id)
    );

    create table horario_atencion (
        hora_fin time(0) not null,
        hora_inicio time(0) not null,
        especialista_id bigint not null,
        id bigint generated by default as identity,
        dia varchar(10) not null check ((dia in ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY'))),
        primary key (id),
        constraint uk_horario_especialista_dia unique (especialista_id, dia)
    );

    create table interno (
        activo boolean not null,
        cuota_mensual numeric(10,2),
        fecha_ingreso date not null,
